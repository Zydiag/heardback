#!/usr/bin/env python3
"""Write public/docs/commands.md from the verb catalogue (`jv list --json`, as heardback.brain.catalogue reads it).

Runs jv with an empty HOME/XDG so the user's own actions never reach the public doc.
Usage: uv run python scripts/gen-commands-doc.py
"""
import json
import re
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "docs" / "commands.md"
CONFIRM = {True: "always", "auto": "sometimes", False: "no"}


def catalogue() -> list[dict]:
    with tempfile.TemporaryDirectory() as home:
        env = {**os.environ, "HOME": home, "XDG_CONFIG_HOME": home, "XDG_STATE_HOME": home,
               "XDG_DATA_HOME": home, "HEARDBACK_CONFIG": str(Path(home) / "none.toml")}
        out = subprocess.run([sys.executable, "-c", "from jv.cli import main; main()", "list", "--json"],
                             env=env, capture_output=True, text=True, check=True).stdout
    return json.loads(out)["verbs"]


def first_sentence(s: str) -> str:
    """Descriptions double as model instructions; the table keeps only the first sentence."""
    return re.split(r"(?<=[.!?])(?<!e\.g\.)\s+", s.strip(), maxsplit=1)[0]


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render(verbs: list[dict]) -> str:
    lines = ["# Commands", "",
             "Generated by `scripts/gen-commands-doc.py` from the verb catalogue (`jv list --json`). Do not edit by hand.",
             "", "Every action heardback can take is a `jv` verb. Run any of them from a terminal; add `--dry-run` "
             "to see what would happen, including the read-back a confirmed verb asks for.", "",
             "- **Confirm**: *always* = read back and needs a spoken yes; *sometimes* = `jv` decides per call "
             "(for example, Enter into a pane that is not a Claude session); *no* = runs directly.",
             "- **Effect**: what the verb does to your desktop. *unknown* verbs are treated like destructive ones.",
             "- **Phrases** reach the verb on the fast path, without a model. `{name}` is a slot; `(x )?` is optional. "
             "Anything else goes to Claude, which can call the same verbs.",
             "- **Voice**: *no* = terminal only; neither the fast path nor Claude can call it.", ""]
    for domain in dict.fromkeys(v["domain"] for v in verbs):
        lines += [f"## {domain}", "", "| Command | What it does | Effect | Confirm | Voice | Phrases |", "|---|---|---|---|---|---|"]
        for v in (v for v in verbs if v["domain"] == domain):
            cmd = "jv " + v["name"].replace(".", " ")
            phrases = "<br>".join(f"`{cell(p)}`" for p in v["phrases"][:3])
            voice = "yes" if v.get("voice", True) and v.get("claude", True) else "no" if not v.get("voice", True) else "fast path only"
            lines.append(f"| `{cmd}` | {cell(first_sentence(v['description']))} | {v['effect']} | {CONFIRM.get(v['confirm'], str(v['confirm']))} "
                         f"| {voice} | {phrases} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(catalogue()))
    print(f"wrote {OUT.relative_to(ROOT)}")
